#!/usr/bin/env python3
"""Generate the self-contained belief deck library used by the bot.

The Kaggle bundle only contains main.py, deck.csv and cg/.  Opponent archetype
templates therefore have to be embedded as a Python module instead of being
read from decks/ at runtime.

Run after updating the replay-mined deck lists:

    python3 tools/build_belief_data.py
"""

from __future__ import annotations

from pathlib import Path

